import os; _R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
"""ملاحظات الجوال (٢٥ أكتوبر): لوحة العنصر تتبع التحديد، عناصر مستقلة لكل بند، ترتيب حرّ للطبقات، أدوات الصورة، تراجع سريع، وشريط أدوات لا يقفز."""
import asyncio, sys
sys.path.insert(0, _R + '/v6')
from t6 import setup, URL, OUT, THM
from playwright.async_api import async_playwright
def ok(c, m): print(('✓ ' if c else '✗ ') + m, flush=True)
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width': 1440, 'height': 900})
        errs = await setup(pg)
        await pg.goto(URL + '#/e/ishraq/cover_schedule'); await pg.wait_for_timeout(3000)
        await pg.evaluate("document.querySelectorAll('.coach,.gintro').forEach(x=>x.remove())")
        g = await pg.evaluate("Object.keys(LASTG).filter(k=>/^row\\d/.test(k))")
        ok(len(g) == 3, 'each meeting row is its own element: %s' % g)
        await pg.evaluate("openElPanel('row1')"); await pg.wait_for_timeout(500)
        await pg.evaluate("select('title')"); await pg.wait_for_timeout(500)
        ok(await pg.evaluate("ED.elG") == 'title', 'element settings follow the newly selected element')
        ok('الصف ٢' in await pg.evaluate("gName('row1')"), 'numbered element names in Arabic: ' + await pg.evaluate("gName('row1')"))
        # توسيط عنصر مفرد
        await pg.evaluate("select('row1'); const bx=LASTG['row1']; S.sel='row1'; moveSel(SIZES[S.size].w/2-(bx.x0+bx.x1)/2, 0); changed6(); drawNow()"); await pg.wait_for_timeout(600)
        c = await pg.evaluate("(LASTG['row1'].x0+LASTG['row1'].x1)/2 - SIZES[S.size].w/2")
        ok(abs(c) < 2, 'centering a single row lands in the middle (off by %.1f)' % c)
        # الطبقات: صورة مضافة تنزل تحت عناصر القالب
        await pg.evaluate("addLayer6({t:'img', ref:'lib:img_dome', w:0.9})"); await pg.wait_for_timeout(800)
        lid = await pg.evaluate("S.sel")
        n = await pg.evaluate("stackOrder().all.length")
        for _ in range(n): await pg.evaluate("l => moveInStack(l, -1)", lid)
        await pg.wait_for_timeout(600)
        st = await pg.evaluate("l => { const o=stackOrder(); return {i:o.all.indexOf(l), front:S.front.length, title:o.all.indexOf('title')} }", lid)
        ok(st['i'] == 0 and st['title'] > 0, 'added image moved below every template element: %s' % st)
        ok(await pg.evaluate("l => ED.proxies[l].zIndex() < ED.proxies['title'].zIndex()", lid), 'title stays selectable above the image')
        px = await pg.evaluate("""() => { const c=document.createElement('canvas'); renderTo(c,S.tpl,S.size,snap(),S.track,1); const g=c.getContext('2d'); const b=LASTG['title']; const d=g.getImageData(0,0,c.width,c.height).data; return d.length>0 }""")
        ok(px, 'renders with the interleaved order')
        # أدوات الصورة
        await pg.evaluate("l => { const L=layerById(l.slice(2)); L.fx={gs:1}; changed6(); drawNow(); }", lid); await pg.wait_for_timeout(700)
        gray = await pg.evaluate("""l => { const L=layerById(l.slice(2)); const c=document.createElement('canvas'); const st=snap(); st.layers=[L]; st.front=[]; st.hide=Object.assign({},st.hide); Object.keys(LASTG).forEach(k=>{ if(!k.startsWith('L:')) st.hide['g_'+k]=true; }); renderTo(c,S.tpl,S.size,st,S.track,0.5); const g=c.getContext('2d'); const d=g.getImageData(Math.round(c.width*L.x),Math.round(c.height*L.y),1,1).data; return [d[0],d[1],d[2]]; }""", lid)
        ok(max(gray) - min(gray) <= 3, 'black & white filter applied: %s' % gray)
        await pg.evaluate("l => { const L=layerById(l.slice(2)); L.fx={}; L.mk='circle'; L.cr=1; L.bw=0.03; L.sh=0.6; L.fe=0.3; L.tc='#ff0000'; L.ta=0.3; L.fh=true; changed6(); drawNow(); }", lid); await pg.wait_for_timeout(600)
        ok(await pg.evaluate("l => { const b=LASTG[l]; return Math.abs((b.x1-b.x0)-(b.y1-b.y0)) < 3 }", lid), 'square crop for the circle mask')
        await pg.evaluate("l => openElPanel(l)", lid); await pg.wait_for_timeout(600)
        t = await pg.evaluate("(document.querySelector('.imgtools')||{}).textContent||''")
        ok('تعديل الصورة' in t and 'القصّ والشكل' in t and 'تلاشي الأطراف' in t and document_has(t), 'image tools panel for an added image')
        ok(await pg.evaluate("document.querySelectorAll('.imgtools .fxb').length") == 9, 'nine filter presets with previews')
        await pg.screenshot(path=OUT + 'aa1_imgtools.png')
        # خانة صورة في القالب
        await pg.evaluate("ED.leaveOK=true"); await pg.goto(URL + '#/e/ishraq/ann_photo'); await pg.wait_for_timeout(2500)
        await pg.evaluate("document.querySelectorAll('.coach,.gintro').forEach(x=>x.remove())")
        await pg.evaluate("openElPanel('photo')"); await pg.wait_for_timeout(600)
        ok(await pg.evaluate("!!document.querySelector('.imgtools')"), 'template photo element has image tools')
        await pg.evaluate("S.d.photo.fx={sp:1}; changed6(); drawNow()"); await pg.wait_for_timeout(500)
        ok(await pg.evaluate("snap().d.photo.fx.sp") == 1, 'filter saved with the design')
        # المحاذاة وتأثيرات النص
        await pg.evaluate("addLayer6({t:'text', txt:'نص تجربة للمحاذاة', w:0.5, sz:0.06})"); await pg.wait_for_timeout(600)
        tl = await pg.evaluate("S.sel")
        await pg.evaluate("l => openElPanel(l)", tl); await pg.wait_for_timeout(500)
        ok(await pg.evaluate("document.querySelectorAll('.albar .alb').length") == 6, 'alignment bar with six directions')
        await pg.click('.albar .alb[title="إلى الأعلى"]'); await pg.wait_for_timeout(500)
        top = await pg.evaluate("l => LASTG[l].y0 - margin()", tl)
        ok(abs(top) < 2, 'align to top margin (off by %.1f)' % top)
        ok('تأثيرات النص' in await pg.evaluate("document.querySelector('#e_panel').textContent"), 'text effects section for added text')
        await pg.evaluate("l => { const L=layerById(l.slice(2)); L.bgc='#222222'; L.olc='#ffffff'; L.olw=0.1; L.ts=0.6; L.lh=1.6; changed6(); drawNow(); }", tl); await pg.wait_for_timeout(500)
        await pg.screenshot(path=OUT + 'aa2_text.png')
        await pg.evaluate("ED.leaveOK=true")
        # الجوال
        ctx = await b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, is_mobile=True, has_touch=True)
        m = await ctx.new_page(); APP = URL.replace('index.html', 'app.html')
        await m.goto(APP); await m.evaluate("localStorage.clear()"); await m.goto(APP + '#/login'); await m.wait_for_timeout(1000)
        await m.evaluate("DEMO.reset()"); await m.evaluate("DEMO.seed(%s)" % THM); await m.wait_for_timeout(300)
        await m.fill('#lg_id', 'admin'); await m.fill('#lg_pw', 'Admin#2026'); await m.click('.lgform button[type=submit]')
        await m.wait_for_selector('.mtab:not([hidden])', timeout=60000); await m.wait_for_timeout(1500); await m.evaluate("closeModals()")
        await m.goto(APP + '#/e/ishraq/ann_panel'); await m.wait_for_timeout(3000)
        await m.evaluate("document.querySelectorAll('.coach,.gintro,.msheet-wrap').forEach(x=>x.remove())")
        ok(await m.evaluate("!!document.querySelector('#e_mundo')"), 'quick undo button in the mobile top bar')
        await m.evaluate("S.d.title='تجربة'; changed6(); pushUndo6()"); await m.wait_for_timeout(700)
        ok(not await m.evaluate("document.querySelector('#e_mundo').disabled"), 'undo enabled after a change')
        await m.evaluate("const r=document.querySelector('.mrail'); r.scrollLeft = -120"); await m.wait_for_timeout(300)
        x0 = await m.evaluate("document.querySelector('.mrail').scrollLeft")
        await m.evaluate("const r=document.querySelector('.mrail'); const rb=r.getBoundingClientRect(); const b=[...r.querySelectorAll('button')].find(x=>{const q=x.getBoundingClientRect(); return q.left>rb.left+20 && q.right<rb.right-20 && !x.classList.contains('on')}); b.click()"); await m.wait_for_timeout(120)
        x1 = await m.evaluate("document.querySelector('.mrail').scrollLeft")
        ok(abs(x1 - x0) < 2, 'tool rail keeps its position when a visible tool is tapped (%s → %s)' % (x0, x1))
        print('ERRORS', [e for e in errs if '404' not in e][:5]); await b.close()
def document_has(t): return True
if __name__ == "__main__": asyncio.run(main())
