import os; _R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
"""أدوات الدرس: نموذج قوقل للأسئلة، الأسماء والفرق، كاهوت (تصدير واستيراد)، ورقة العمل، وفي العرض: القلم والقرعة والنقاط والنتائج."""
import asyncio, sys, json
sys.path.insert(0, _R + '/v6')
from t6 import setup, URL, OUT
from playwright.async_api import async_playwright
def ok(c, m): print(('✓ ' if c else '✗ ') + m, flush=True)
async def clean(pg):
    for _ in range(3):
        await pg.evaluate("document.querySelectorAll('.coach,.gintro').forEach(x=>x.remove())")
        if await pg.query_selector('.modal'): await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
QS = [{'q': 'ما أول ما نزل من القرآن؟', 'opts': ['الفاتحة', 'اقرأ', 'المدثر', 'الإخلاص'], 'ans': 2}, {'q': 'كم عدد سور القرآن؟', 'opts': ['١١٤', '١١٠', '١٢٠'], 'ans': 1}]
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        ctx = await b.new_context(viewport={'width': 1440, 'height': 900}, accept_downloads=True)
        pg = await ctx.new_page()
        errs = await setup(pg)
        await pg.goto(URL + '#/s/ithmar'); await pg.wait_for_timeout(1500)
        await pg.evaluate("openDeckNew('ithmar', sampleDecks(trackOf('ithmar'))[1].slides, 'درس التجربة')"); await pg.wait_for_timeout(2500); await clean(pg)
        # كاهوت: ملف بالقالب الرسمي ثم استيراده إلى شرائح
        rows = await pg.evaluate("qs => { ED.doc.name='درس التجربة'; return kahootRows(qs, 20); }", QS)
        ok(rows[7][1] == 'Question - 120 max length' and rows[7][7] == 'Correct answer(s)' and rows[8] == [1, QS[0]['q'], 'الفاتحة', 'اقرأ', 'المدثر', 'الإخلاص', 20, '2'], 'Kahoot rows follow the official template (headers row 8, data row 9)')
        back = await pg.evaluate("async qs => { const blob = kahootXlsx(qs, 20); const rows = await readXlsx(await blob.arrayBuffer()); return quizFromRows(rows); }", QS)
        ok(back == QS, 'Kahoot file reads back to the same questions: %s' % back)
        n0 = await pg.evaluate("ED.doc.pages.length")
        await pg.evaluate("async qs => { const blob = kahootXlsx(qs, 20); await importQuiz(new File([blob], 'k.xlsx')); }", QS); await pg.wait_for_timeout(1200)
        st = await pg.evaluate("({n: ED.doc.pages.length, q: ED.doc.pages.filter(p=>p.tpl==='sl_quiz').map(p=>p.d.q), cur: S.tpl.id})")
        ok(st['n'] == n0 + 2 and QS[0]['q'] in st['q'] and st['cur'] == 'sl_quiz', 'imported questions became quiz slides: %s' % st)
        # simple sheet (no Kahoot header)
        simple = await pg.evaluate("async () => { const blob = xlsxOf([['ما عاصمة الإسلام الأولى؟', 'مكة', 'المدينة', '2']]); return quizFromRows(await readXlsx(await blob.arrayBuffer())); }")
        ok(simple == [{'q': 'ما عاصمة الإسلام الأولى؟', 'opts': ['مكة', 'المدينة'], 'ans': 2}], 'simple table import: %s' % simple)
        # بطاقة أدوات الدرس
        await pg.evaluate("openTab('content')"); await pg.wait_for_timeout(600)
        ok(await pg.evaluate("document.querySelectorAll('.lessonsec .ltile').length") == 4, 'lesson tools card with four tools')
        await pg.evaluate("document.querySelector('.lessonsec').scrollIntoView()"); await pg.wait_for_timeout(300)
        await pg.screenshot(path=OUT + 'ac1_panel.png')
        # الأسماء والفرق
        await pg.click('.ltile:has-text("الأسماء والفرق")'); await pg.wait_for_timeout(400)
        await pg.fill('.modal textarea', 'أحمد\nخالد\nعمر\nيوسف')
        await pg.click('.modal .acts .btn.dark'); await pg.wait_for_timeout(400)
        ok(await pg.evaluate("JSON.stringify(ED.doc.lesson.names)") == json.dumps(['أحمد', 'خالد', 'عمر', 'يوسف'], ensure_ascii=False, separators=(',', ':')) and await pg.evaluate("ED.doc.lesson.teams.length") == 2, 'names and two default teams saved with the deck')
        # نموذج قوقل
        await pg.click('.ltile:has-text("إجابات الطلاب")'); await pg.wait_for_timeout(400)
        ok(await pg.evaluate("document.querySelectorAll('.modal .fqs li').length") >= 2, 'form dialog lists the deck questions')
        await pg.click('.modal .btn.dark:has-text("أنشئ النموذج")'); await pg.wait_for_timeout(1500)
        f = await pg.evaluate("ED.doc.lesson.form")
        ok(f and 'forms.gle' in f['url'] and QS[0]['q'] in f['qs'], 'Google Form created for the deck: %s' % (f and f['url']))
        await pg.evaluate("f => { const k = f.qs.indexOf(%s); const a = {}; a[k] = 'اقرأ'; GAS._formAnswer(f.id, a); GAS._formAnswer(f.id, a); const b = {}; b[k] = 'الفاتحة'; GAS._formAnswer(f.id, b); }" % json.dumps(QS[0]['q'], ensure_ascii=False), f)
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await pg.click('.ltile:has-text("إجابات الطلاب")'); await pg.wait_for_timeout(1200)
        t = await pg.inner_text('.modal .fres')
        ok('٣ طالباً أجابوا' in t, 'results summary in the editor: ' + t[:60].replace('\n', ' '))
        await pg.screenshot(path=OUT + 'ac2_form.png')
        await pg.click('.modal .btn:has-text("رمز الدخول في هذه الشريحة")'); await pg.wait_for_timeout(600)
        ok(await pg.evaluate("S.layers.some(l=>l.t==='qr' && l.url===ED.doc.lesson.form.url) && S.layers.some(l=>l.txt==='امسح وأجب')"), 'join QR added to the slide')
        # العرض: الأدوات
        qi = await pg.evaluate("ED.doc.pages.findIndex(p=>p.tpl==='sl_quiz' && p.d.q===%s)" % json.dumps(QS[0]['q'], ensure_ascii=False))
        await pg.evaluate("i => { present6(false, i); }", qi); await pg.wait_for_timeout(1500)
        ok(await pg.evaluate("['القلم والتحديد والليزر (P)','القرعة (R)','نقاط الفرق (S)','إجابات الطلاب (Q)'].every(t=>document.querySelector('.pbar .pb[title=\"'+t+'\"]'))"), 'presentation bar has pen, draw, scores and results')
        await pg.keyboard.press('p'); await pg.wait_for_timeout(300)
        ok(await pg.evaluate("!document.querySelector('.ppen').hidden"), 'P opens the pen palette')
        bx = await pg.evaluate("(()=>{const r=document.querySelector('.pdraw').getBoundingClientRect(); return [r.left,r.top,r.width,r.height]})()")
        await pg.mouse.move(bx[0] + bx[2] * 0.3, bx[1] + bx[3] * 0.5); await pg.mouse.down()
        for k in range(12): await pg.mouse.move(bx[0] + bx[2] * (0.3 + k * 0.03), bx[1] + bx[3] * (0.5 + (k % 3) * 0.02))
        await pg.mouse.up(); await pg.wait_for_timeout(200)
        await pg.keyboard.press('h')
        await pg.mouse.move(bx[0] + bx[2] * 0.3, bx[1] + bx[3] * 0.3); await pg.mouse.down(); await pg.mouse.move(bx[0] + bx[2] * 0.7, bx[1] + bx[3] * 0.3, steps=8); await pg.mouse.up()
        idx = await pg.evaluate("document.querySelector('.present6')._lesson ? 1 : 0")
        n = await pg.evaluate("(()=>{ const o=document.querySelector('.present6')._lesson; return Object.values(o.pen.strokes).flat().map(s=>s.t) })()")
        ok(idx and n == ['pen', 'marker'], 'pen and highlighter strokes on the slide: %s' % n)
        ok(await pg.evaluate("(()=>{const c=document.querySelector('.pdraw'); const g=c.getContext('2d'); const d=g.getImageData(0,0,c.width,c.height).data; let k=0; for(let i=3;i<d.length;i+=4) if(d[i]) k++; return k>500})()"), 'ink is drawn')
        await pg.screenshot(path=OUT + 'ac3_pen.png')
        cur = await pg.evaluate("document.querySelector('.pcount').textContent")
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        ok(await pg.evaluate("!!document.querySelector('.present6') && document.querySelector('.ppen').hidden") and await pg.evaluate("document.querySelector('.pcount').textContent") == cur, 'Escape leaves the pen, not the presentation')
        # النقاط
        await pg.keyboard.press('s'); await pg.wait_for_timeout(300)
        await pg.click('.pscore .sct >> nth=0 >> .scb'); await pg.click('.pscore .sct >> nth=0 >> .scb'); await pg.click('.pscore .sct >> nth=1 >> .scb'); await pg.wait_for_timeout(300)
        ok(await pg.evaluate("ED.doc.lesson.teams.map(t=>t.p).join(',')") == '2,1', 'team points added during the presentation')
        await pg.click('.pscore .sct >> nth=1 >> .scm'); await pg.wait_for_timeout(200)
        ok(await pg.evaluate("ED.doc.lesson.teams[1].p") == 0 and await pg.evaluate("document.querySelector('.pscore .sct').classList.contains('lead')"), 'minus button and leader highlight')
        # القرعة
        await pg.keyboard.press('r'); await pg.wait_for_timeout(300)
        await pg.click('.pkgo'); await pg.wait_for_timeout(2600)
        w = await pg.evaluate("document.querySelector('.pkname.won') && document.querySelector('.pkname').textContent")
        ok(w in ['أحمد', 'خالد', 'عمر', 'يوسف'], 'picker chose a student: %s' % w)
        picks = [w]
        for _ in range(3): await pg.click('.pkgo'); await pg.wait_for_timeout(2600); picks.append(await pg.evaluate("document.querySelector('.pkname').textContent"))
        ok(sorted(picks) == sorted(['أحمد', 'خالد', 'عمر', 'يوسف']), 'no repeats until everyone is picked: %s' % picks)
        await pg.screenshot(path=OUT + 'ac4_picker.png')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        ok(await pg.evaluate("!document.querySelector('.ppick') && !!document.querySelector('.present6')"), 'Escape closes the picker only')
        # النتائج
        await pg.keyboard.press('q'); await pg.wait_for_timeout(1500)
        rt = await pg.inner_text('.pres')
        ok('٣ أجابوا' in rt and '٢ · ٦٧٪' in rt, 'live results on the quiz slide: ' + rt.replace('\n', ' ')[:80])
        await pg.screenshot(path=OUT + 'ac5_results.png')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(400)
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(600)
        ok(not await pg.evaluate("!!document.querySelector('.present6')"), 'presentation closes')
        # ورقة العمل في لسان جديد
        async with ctx.expect_page() as np:
            await pg.evaluate("worksheetFromDeck()")
        ws = await np.value; await ws.wait_for_timeout(3500)
        info = await ws.evaluate("({tpl: S.tpl && S.tpl.id, size: S.size, qs: S.d.qs})")
        ok(info['tpl'] == 'st_work' and info['size'] == 'a4' and QS[0]['q'] in info['qs'] and 'اختيار: الفاتحة؛ اقرأ' in info['qs'], 'worksheet opened from the deck questions')
        await ws.evaluate("document.querySelectorAll('.coach,.gintro').forEach(x=>x.remove())"); await ws.screenshot(path=OUT + 'ac6_worksheet.png')
        # البرنامج بالأرقام
        await pg.evaluate("ED.leaveOK=true")
        await pg.evaluate("async () => { const p = V6.prog.id, ev = []; for (let i=0;i<5;i++) ev.push({e:'export', tpl:'ann_panel', p:p}); ev.push({e:'open', tpl:'cover_schedule', p:p}, {e:'present', p:p}, {e:'export', tpl:'st_work', p:p}); await API6.me('stat_track', JSON.stringify(ev)); }")
        await pg.goto(URL + '#/admin/pstats'); await pg.wait_for_timeout(3500)
        t = await pg.inner_text('#abody')
        ok('البرنامج بالأرقام' in t and 'نُشر في القناة' in t and 'العروض المقدَّمة' in t, 'programme stats page with KPIs')
        ok(await pg.evaluate("document.querySelectorAll('.pstpl').length") >= 2 and 'مواد تعليمية' in t and 'قوالب لم تُستعمل' in t, 'top templates with thumbnails, by type, unused templates')
        await pg.screenshot(path=OUT + 'ac7_pstats.png', full_page=True)
        errs2 = [e for e in errs if '404' not in e]; print('ERRORS', errs2[:3])
        await b.close()
asyncio.run(main())
